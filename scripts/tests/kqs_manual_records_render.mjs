import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const code = await readFile(new URL('../../app/frontend/js/views/kqsManualRecords.js', import.meta.url), 'utf8');
const { manualRequest, resetManualRequest, kstTradeAt, kstRecordTime } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
assert.equal(kstTradeAt('2026-09-30T09:15'), '2026-09-30T00:15:00.000Z');
assert.equal(kstTradeAt(''), null);
assert.throws(() => kstTradeAt('<script>'));
assert.equal(kstRecordTime('2026-09-30T00:15:00'), kstRecordTime('2026-09-30T00:15:00Z'));
assert.ok(kstRecordTime('2026-09-30T00:15:00Z').includes('9:15'));
const form = {}, body = { decision: 'buy', quantity: 2 };
let sequence = 0;
const next = () => 'manual-request-' + (++sequence);
const first = manualRequest(form, body, next);
assert.deepEqual(manualRequest(form, body, next), first);
assert.notEqual(manualRequest(form, { ...body, quantity: 3 }, next).request_id, first.request_id);
resetManualRequest(form);
assert.notEqual(manualRequest(form, body, next).request_id, first.request_id);
assert.ok(/^kqs-[a-f0-9]{32}$/.test(manualRequest({}, body).request_id));
const view = await readFile(new URL('../../app/frontend/js/views/strategyList.js', import.meta.url), 'utf8');
assert.equal((view.match(/JSON.stringify\(manualRequest\(form,/g) || []).length, 2);
assert.ok(view.includes('form.dataset.kqsSaving'));
assert.ok(view.includes('recorded_at || item.decided_at'));
assert.ok(view.includes("escapeHtml((item.evidence_tags || []).join(', ') || '-')"));
const recommendationSource = await readFile(new URL('../../app/frontend/js/views/kqsRecommendations.js', import.meta.url), 'utf8');
const { kqsRecommendationsHtml } = await import(`data:text/javascript;base64,${Buffer.from(recommendationSource).toString('base64')}`);
const html = kqsRecommendationsHtml({ read_only: true, signals: [{ signal_id: 'one', reasons: [], action: 'entry' }] });
assert.ok(html.includes('data-kqs-trade-at'));
assert.ok(html.includes('data-kqs-new-record'));
console.log('KQS manual records: KST conversion/time display/stable retry ID/new intent/submit wiring passed');
